-- ============================================
-- WebGame 战斗系统 - 等级配置表
-- 用于存储每个等级所需的经验值阈值
-- ============================================

CREATE TABLE IF NOT EXISTS `wg_level_config` (
  `level` INT NOT NULL COMMENT '等级',
  `exp_required` BIGINT NOT NULL COMMENT '升级所需总经验值',
  `exp_to_next` BIGINT DEFAULT NULL COMMENT '升到下一级所需经验',
  `stat_points` INT DEFAULT 5 COMMENT '升级获得的属性点',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  
  PRIMARY KEY (`level`) USING BTREE,
  KEY `idx_exp_required` (`exp_required`) USING BTREE COMMENT '经验值索引'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='等级配置表';

